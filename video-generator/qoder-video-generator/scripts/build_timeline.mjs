// Generate remotion/src/data/timeline.ts from spec/shotlist.json + assets/audio/timing.json
// One source of truth: narration timings are measured, shots are rounded to whole frames
// and made contiguous so there are no gaps or overlaps in the film.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.cwd());
const spec = JSON.parse(fs.readFileSync(path.join(root, "spec/shotlist.json"), "utf8"));
const timing = JSON.parse(fs.readFileSync(path.join(root, "assets/audio/timing.json"), "utf8"));

const FPS = spec.canvas.fps;
const FILM_FRAMES = Math.round(timing.total_duration_s * FPS);

const lineByText = new Map(timing.lines.map((l) => [l.text, l]));
const used = new Set();

const lines = timing.lines.map((l) => ({
  i: l.line,
  text: l.text,
  start: Math.round(l.start * FPS),
  end: Math.round(l.end * FPS),
}));

const starts = spec.shots.map((s) => Math.round(s.start_s * FPS));
const shots = spec.shots.map((s, idx) => {
  const start = starts[idx];
  const next = idx + 1 < starts.length ? starts[idx + 1] : FILM_FRAMES;
  const texts = s.narration ? s.narration.split("\n").map((x) => x.trim()).filter(Boolean) : [];
  const lineIds = texts.map((t) => {
    const hit = lineByText.get(t);
    if (!hit) throw new Error(`Narration line not found in timing.json: ${t}`);
    used.add(hit.line);
    return hit.line;
  });
  return {
    id: s.id,
    act: s.act,
    start,
    dur: next - start,
    lines: lineIds,
    tech: s.tech,
    asset: s.asset ?? null,
    visual: s.visual,
    sourceNote: s.source_note ?? "",
  };
});

const missing = timing.lines.filter((l) => !used.has(l.line)).map((l) => l.line);
if (missing.length) throw new Error(`Timing lines not assigned to shots: ${missing.join(", ")}`);

const header = `// AUTO-GENERATED by scripts/build_timeline.mjs — do not edit by hand.
// Source: spec/shotlist.json + assets/audio/timing.json (measured TTS)
export type Line = { i: number; text: string; start: number; end: number };
export type Shot = {
  id: string;
  act: string;
  start: number;
  dur: number;
  lines: number[];
  tech: string;
  asset: string | null;
  visual: string;
  sourceNote: string;
};

export const FPS = ${FPS};
export const FILM_FRAMES = ${FILM_FRAMES};
export const LINES: Line[] = ${JSON.stringify(lines, null, 2)};
export const SHOTS: Shot[] = ${JSON.stringify(shots, null, 2)};
`;

fs.writeFileSync(path.join(root, "remotion/src/data/timeline.ts"), header);
console.log(
  `timeline.ts: ${shots.length} shots, ${lines.length} lines, ${FILM_FRAMES} frames (${(
    FILM_FRAMES / FPS
  ).toFixed(3)}s)`,
);
